"""Collects each scenario's result and generates the eval table from the test run."""

from pathlib import Path

import pytest

from harness import SCENARIOS as _scenarios
from harness import EvalEnv

TABLE_PATH = Path(__file__).resolve().parents[2] / "eval_results.md"
@pytest.fixture
def env(tmp_path, monkeypatch):
    return EvalEnv(tmp_path, monkeypatch)


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    report = outcome.get_result()
    if report.when == "call" and report.failed and item.originalname in _scenarios:
        _scenarios[item.originalname]["notes"] = str(call.excinfo.value).splitlines()[0][:200]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def pytest_sessionfinish(session, exitstatus):
    if not _scenarios:
        return
    rows = sorted(_scenarios.values(), key=lambda row: row["number"])
    passed = sum(1 for row in rows if row["result"] == "PASS")
    lines = [
        "# Eval results",
        "",
        "Generated by `uv run pytest`. Do not edit by hand.",
        "",
        f"{passed} of {len(rows)} scenarios passed.",
        "",
        "| # | Scenario | Expected | Actual | Result | Notes |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(f"| {row['number']} | {_cell(row['name'])} | {_cell(row['expected'])} | {_cell(row['actual'])} | {row['result']} | {_cell(row['notes'])} |")
    TABLE_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
